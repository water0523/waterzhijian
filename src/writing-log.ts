import {createWritingJournal} from './writing-journal';
import type {WritingLog,WritingLogEntry} from './writing-data';
export * from './writing-data';
export type {WritingSaveStatus} from './writing-journal';
let queued=false;
const journal=createWritingJournal(()=>{if(queued)return;queued=true;queueMicrotask(()=>{queued=false;window.dispatchEvent(new Event('paper-writing-log'));});});
window.addEventListener('storage',e=>{if(e.key==='paper-writing-log'||e.key?.startsWith('paper-writing-outbox-v1-')){void journal.recover();window.dispatchEvent(new Event('paper-writing-log'));}});
export const readWritingLog=(now=new Date())=>journal.read(now);
export const readJournalAwards=()=>journal.readAwards();
export const saveJournalAwards=(value:Record<string,string>)=>journal.saveAwards(value);
export const writingSaveStatus=()=>journal.status();
export const recordWriting=(day:string,delta:Partial<WritingLogEntry>,now=new Date())=>journal.record(day,delta,now);
export const flushWritingLog=(force=false)=>journal.flush(force);
export const recoverWritingLog=()=>journal.recover();
export const mergeWritingRecords=(log:WritingLog,awards:Record<string,string>)=>journal.merge(log,awards);
